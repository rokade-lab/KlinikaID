CREATE TABLE patients (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medical_record_no text NOT NULL UNIQUE,
    full_name         text NOT NULL,
    birth_date        date NOT NULL,
    phone             text,
    address           text,
    created_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      text NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role          text NOT NULL CHECK (role IN ('patient', 'doctor', 'frontdesk', 'admin')),
    display_name  text NOT NULL,
    patient_id    bigint NULL REFERENCES patients (id),
    active        boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_patient_role_check CHECK ((role = 'patient') = (patient_id IS NOT NULL))
);
CREATE INDEX users_patient_id_idx ON users (patient_id);

CREATE TABLE visits (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id         bigint NOT NULL REFERENCES patients (id),
    visit_date         date NOT NULL,
    department         text NOT NULL,
    medical_note_dummy text NOT NULL,
    created_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX visits_patient_id_idx ON visits (patient_id, visit_date);

CREATE TABLE doctor_assignments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id   bigint NOT NULL REFERENCES users (id),
    visit_id    bigint NOT NULL REFERENCES visits (id),
    active      boolean NOT NULL DEFAULT true,
    assigned_at timestamptz NOT NULL,
    revoked_at  timestamptz NULL,
    CONSTRAINT doctor_assignments_revoked_check CHECK (active OR revoked_at IS NOT NULL)
);
CREATE UNIQUE INDEX doctor_assignments_active_uniq ON doctor_assignments (doctor_id, visit_id) WHERE active;
CREATE INDEX doctor_assignments_visit_id_idx ON doctor_assignments (visit_id);

CREATE TABLE documents (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id     bigint NOT NULL REFERENCES visits (id),
    storage_key  text NOT NULL UNIQUE,
    display_name text NOT NULL,
    mime_type    text NOT NULL,
    size_bytes   integer NOT NULL CHECK (size_bytes >= 0),
    sha256       char(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    created_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT documents_storage_key_format CHECK (storage_key ~ '^docs/[0-9a-f]{2}/[0-9a-f]{64}\.pdf$')
);
CREATE INDEX documents_visit_id_idx ON documents (visit_id);

CREATE TABLE schedules (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id         bigint NOT NULL REFERENCES visits (id),
    operational_time timestamptz NOT NULL,
    room             text NOT NULL,
    status           text NOT NULL
);
CREATE INDEX schedules_visit_id_idx ON schedules (visit_id);
CREATE INDEX schedules_operational_time_idx ON schedules (operational_time);

CREATE TABLE audit_events (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id      bigint NULL,
    action        text NOT NULL,
    resource_type text NOT NULL,
    resource_id   text NULL,
    outcome       text NOT NULL CHECK (outcome IN ('allow', 'deny', 'error')),
    request_id    text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_events_created_at_idx ON audit_events (created_at);

CREATE TABLE sessions (
    id            char(64) PRIMARY KEY,
    user_id       bigint NULL,
    data          text NOT NULL,
    created_at    timestamptz NOT NULL,
    last_activity timestamptz NOT NULL
);
CREATE INDEX sessions_last_activity_idx ON sessions (last_activity);
CREATE INDEX sessions_user_id_idx ON sessions (user_id);

